(() => {
  'use strict';
  const $ = id => document.getElementById(id);
  const params = new URLSearchParams(window.location.search);
  const demoPosts = [{
    slug: 'building-for-low-bandwidth', title: 'Building digital tools for low-bandwidth realities',
    date: '2026-11-16T09:00:00.000Z',
    excerpt: 'A practical look at why lightweight pages, offline-first behaviour and clear interfaces matter when data and device resources are limited.',
    category: 'About Tech', image: '', imageAlt: '', tags: ['Uganda', 'Mobile', 'Digital skills'],
    bodyHtml: '<h2>Start with the conditions people actually have</h2><p>A useful digital product should remain understandable on a small screen, tolerate a slow connection and avoid asking people to download more than they need.</p><ul><li>Keep the first screen fast and focused.</li><li>Save work locally when it is safe to do so.</li><li>Make controls clear to touch and screen readers.</li></ul><p><strong>Demo content:</strong> this is sample text for previewing the publishing layout. It is not a published article.</p>'
  }];
  const state = { posts: [], filtered: [] };
  const search = $('journal-search'), category = $('journal-category');
  const grid = $('journal-grid'), list = $('journal-list'), articleView = $('article-view');
  const safeImage = value => typeof value === 'string' && /^\/assets\/uploads\/[a-zA-Z0-9._/-]+$/.test(value) && !value.split('/').includes('..');
  const formatDate = value => {
    const date = new Date(value);
    return Number.isNaN(date.getTime()) ? '' : new Intl.DateTimeFormat('en-UG', { dateStyle: 'long' }).format(date);
  };
  const setText = (id, value) => { const el = $(id); if (el) el.textContent = value ?? ''; };
  function makeCard(post) {
    const card = document.createElement('article'); card.className = 'journal-card';
    if (safeImage(post.image)) {
      const image = document.createElement('img'); image.className = 'card-image';
      image.src = post.image; image.alt = post.imageAlt || ''; image.loading = 'lazy'; card.append(image);
    }
    const copy = document.createElement('div'); copy.className = 'card-copy';
    const meta = document.createElement('p'); meta.className = 'card-meta';
    meta.textContent = [post.category, formatDate(post.date)].filter(Boolean).join(' · ');
    const title = document.createElement('h3'); title.textContent = post.title;
    const excerpt = document.createElement('p'); excerpt.textContent = post.excerpt;
    const link = document.createElement('a'); link.className = 'read-link';
    const target = new URL(window.location.href);
    target.searchParams.set('slug', post.slug);
    link.href = target.href; link.textContent = 'Read article →';
    copy.append(meta, title, excerpt, link); card.append(copy); return card;
  }
  function renderList() {
    const term = (search?.value || '').trim().toLocaleLowerCase();
    const selected = category?.value || '';
    state.filtered = state.posts.filter(post => {
      const searchable = [post.title, post.excerpt, post.category, ...(post.tags || [])].join(' ').toLocaleLowerCase();
      return (!term || searchable.includes(term)) && (!selected || post.category === selected);
    });
    grid.replaceChildren(...state.filtered.map(makeCard));
    setText('journal-count', `${state.filtered.length} ${state.filtered.length === 1 ? 'article' : 'articles'}`);
    $('journal-empty').hidden = state.filtered.length > 0;
  }
  function renderArticle(post) {
    list.hidden = true; $('journal-tools').hidden = true; articleView.hidden = false;
    setText('article-category', post.category); setText('article-title', post.title);
    setText('article-meta', formatDate(post.date)); setText('article-excerpt', post.excerpt);
    const image = $('article-image');
    if (safeImage(post.image)) { image.src = post.image; image.alt = post.imageAlt || ''; image.hidden = false; }
    else { image.removeAttribute('src'); image.hidden = true; }
    // bodyHtml is generated by build-content.mjs, which escapes raw HTML and emits a small Markdown allow-list.
    $('article-body').innerHTML = post.bodyHtml || '';
    document.title = `${post.title} · Kastine Augak`;
    const backLink = document.querySelector('.back-link');
    if (backLink) { const back = new URL(window.location.href); back.searchParams.delete('slug'); backLink.href = back.href; }
    const canonical = document.querySelector('link[rel="canonical"]');
    if (canonical) { const canonicalUrl = new URL(window.location.href); canonicalUrl.searchParams.delete('demo'); canonical.href = canonicalUrl.href; }
  }
  function populateCategories() {
    const values = [...new Set(state.posts.map(post => post.category).filter(Boolean))].sort();
    category.replaceChildren(new Option('All categories', ''), ...values.map(value => new Option(value, value)));
  }
  async function load() {
    setText('current-year', String(new Date().getFullYear()));
    try {
      const demo = params.get('demo') === '1' || window.location.protocol === 'file:';
      if (demo) {
        state.posts = demoPosts;
        setText('journal-status', 'Demo content only — it is not published on the website.');
      } else {
        const response = await fetch('data/journal.json', { cache: 'no-store' });
        if (!response.ok) throw new Error(`Journal data could not be loaded (${response.status}).`);
        const data = await response.json(); state.posts = Array.isArray(data.posts) ? data.posts : [];
      }
      const slug = params.get('slug');
      if (slug) {
        const post = state.posts.find(item => item.slug === slug);
        if (post) renderArticle(post);
        else { setText('journal-status', 'That article is not available in this build.'); renderList(); }
      } else { populateCategories(); renderList(); }
    } catch (error) {
      setText('journal-status', error.message || 'The journal could not be loaded.');
      setText('journal-count', 'Articles unavailable');
    }
  }
  search?.addEventListener('input', renderList);
  category?.addEventListener('change', renderList);
  load();
})();
